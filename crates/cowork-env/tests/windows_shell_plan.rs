fn decode_utf16le_base64(encoded: &str) -> String {
    let bytes = data_encoding::BASE64
        .decode(encoded.as_bytes())
        .expect("valid base64");
    assert_eq!(bytes.len() % 2, 0);
    let units: Vec<u16> = bytes
        .chunks_exact(2)
        .map(|c| u16::from_le_bytes([c[0], c[1]]))
        .collect();
    String::from_utf16(&units).expect("valid UTF-16")
}

fn expected_args(tail: &[&str]) -> Vec<String> {
    BASE_ARGS
        .iter()
        .chain(tail.iter())
        .map(|s| (*s).to_owned())
        .collect()
}

#[test]
fn encoding_prelude_and_exit_guard_match_ts_text_exactly() {
    assert_eq!(
        powershell_encoding_prelude("win32"),
        "try { [Console]::OutputEncoding = [System.Text.Encoding]::UTF8 } catch {}; \
         $OutputEncoding = [System.Text.Encoding]::UTF8; $env:PYTHONUTF8 = '1'"
    );
    assert_eq!(powershell_encoding_prelude("linux"), "");
    assert_eq!(powershell_encoding_prelude("darwin"), "");
    assert_eq!(
        POWERSHELL_EXIT_CODE_GUARD,
        "if ((Test-Path -LiteralPath variable:\\LASTEXITCODE)) { exit $LASTEXITCODE }"
    );
    assert_eq!(WIN32_ENCODED_COMMAND_LIMIT, 30_000);
    assert_eq!(
        powershell_script("echo hi"),
        format!(
            "{}\necho hi\n{POWERSHELL_EXIT_CODE_GUARD}",
            powershell_encoding_prelude("win32")
        )
    );
}

#[test]
fn encoded_command_plan_matches_ts_byte_for_byte() {
    let env = HashMap::new();
    for (command, golden) in [
        ("echo hi", TS_ECHO_HI_ENCODED),
        (TRICKY_COMMAND, TS_TRICKY_ENCODED),
    ] {
        let plan = build_non_login_shell_plan(command, &env, "win32");
        let args = expected_args(&["-EncodedCommand", golden]);
        assert_eq!(plan.program, "pwsh");
        assert_eq!(plan.args, args);
        assert_eq!(
            plan.candidates,
            vec![
                ShellCandidate {
                    program: "pwsh".to_owned(),
                    args: args.clone(),
                },
                ShellCandidate {
                    program: "powershell.exe".to_owned(),
                    args: args.clone(),
                },
            ]
        );
        assert_eq!(plan.display_command, command);
        assert!(plan.temp_script.is_none());
        assert_eq!(decode_utf16le_base64(golden), powershell_script(command));
        assert_eq!(
            powershell_encoded_command(&powershell_script(command)),
            golden
        );
    }
}

#[test]
fn encoded_command_limit_boundary_switches_to_temp_script() {
    let env = HashMap::new();
    let opts = ShellPlanOptions {
        temp_dir: Some(r"C:\Temp"),
        script_id: Some("abc"),
    };
    // TS: "a".repeat(11029) is the longest such command that still fits -EncodedCommand.
    let fits = "a".repeat(11_029);
    let plan = build_non_login_shell_plan_with(&fits, &env, "win32", opts);
    assert_eq!(plan.args[4], "-EncodedCommand");
    assert!(plan.args[5].len() <= WIN32_ENCODED_COMMAND_LIMIT);
    assert!(plan.temp_script.is_none());

    let too_long = "a".repeat(11_030);
    let plan = build_non_login_shell_plan_with(&too_long, &env, "win32", opts);
    let path = r"C:\Temp\cowork-shell-abc.ps1";
    let args = expected_args(&["-File", path]);
    assert_eq!(plan.args, args);
    assert_eq!(plan.display_command, too_long);
    let script = plan.temp_script.clone().expect("temp script");
    assert_eq!(script.path, PathBuf::from(path));
    assert_eq!(
        script.content,
        format!("\u{feff}{}", powershell_script(&too_long))
    );
    assert_eq!(plan.candidates.len(), 2);
    assert_eq!(plan.candidates[0].program, "pwsh");
    assert_eq!(plan.candidates[1].program, "powershell.exe");
    assert!(plan.candidates.iter().all(|c| c.args == args));
}

#[test]
fn long_command_temp_script_matches_ts_shape() {
    let env = HashMap::new();
    let big = "Write-Output 'x'\n".repeat(1000);
    // TS: content length 17222 UTF-16 units (BOM + prelude + command + guard), same path joins.
    for (temp_dir, expected_path) in [
        (r"C:\Temp", r"C:\Temp\cowork-shell-abc.ps1"),
        (r"C:\Temp\", r"C:\Temp\cowork-shell-abc.ps1"),
        ("D:/tmp/x", r"D:\tmp\x\cowork-shell-abc.ps1"),
    ] {
        let plan = build_non_login_shell_plan_with(
            &big,
            &env,
            "win32",
            ShellPlanOptions {
                temp_dir: Some(temp_dir),
                script_id: Some("abc"),
            },
        );
        let script = plan.temp_script.expect("temp script");
        assert_eq!(script.path, PathBuf::from(expected_path));
        assert_eq!(script.content.encode_utf16().count(), 17_222);
        assert!(script.content.starts_with(
            "\u{feff}try { [Console]::OutputEncoding = [System.Text.Encoding]::UTF8 } catch {}; "
        ));
        assert!(
            script
                .content
                .ends_with(&format!("\n{POWERSHELL_EXIT_CODE_GUARD}"))
        );
        assert_eq!(plan.args[5], expected_path);
    }

    // Default script id is a fresh UUID under the OS temp dir.
    let a = build_non_login_shell_plan(&big, &env, "win32");
    let b = build_non_login_shell_plan(&big, &env, "win32");
    let (a, b) = (a.temp_script.unwrap(), b.temp_script.unwrap());
    assert_ne!(a.path, b.path);
    let name = a.path.to_string_lossy().into_owned();
    let file = name.rsplit(['\\', '/']).next().unwrap();
    let id = file
        .strip_prefix("cowork-shell-")
        .and_then(|f| f.strip_suffix(".ps1"))
        .expect("cowork-shell-<id>.ps1");
    assert!(uuid::Uuid::parse_str(id).is_ok(), "{id}");
}

#[test]
fn posix_plan_has_no_temp_script_and_keeps_raw_command() {
    let mut env = HashMap::new();
    env.insert("PATH".to_owned(), "/usr/bin:/bin".to_owned());
    let big = "echo x\n".repeat(10_000);
    let plan = build_non_login_shell_plan(&big, &env, "linux");
    assert_eq!(plan.args, vec!["-c".to_owned(), big.clone()]);
    assert_eq!(plan.display_command, big);
    assert!(plan.temp_script.is_none());
}

fn win_env(path: &str, pathext: Option<&str>) -> HashMap<String, String> {
    let mut env = HashMap::new();
    env.insert("Path".to_owned(), path.to_owned());
    if let Some(ext) = pathext {
        env.insert("PATHEXT".to_owned(), ext.to_owned());
    }
    env
}

#[test]
fn candidate_selection_prefers_resolved_pwsh_and_falls_back_to_powershell_exe() {
    let plan = build_non_login_shell_plan("echo hi", &HashMap::new(), "win32");
    let env = win_env(
        r"C:\Program Files\PowerShell\7;C:\Windows\System32\WindowsPowerShell\v1.0",
        None,
    );

    let both = |p: &str| {
        p == r"C:\Program Files\PowerShell\7\pwsh.exe"
            || p == r"C:\Windows\System32\WindowsPowerShell\v1.0\powershell.exe"
    };
    let chosen = select_shell_candidate_with(&plan, &env, "win32", &both).unwrap();
    assert_eq!(chosen.program, r"C:\Program Files\PowerShell\7\pwsh.exe");
    assert_eq!(chosen.args, plan.args);

    // pwsh missing: the missing shell is skipped (TS ENOENT fallback).
    let only_ps = |p: &str| p == r"C:\Windows\System32\WindowsPowerShell\v1.0\powershell.exe";
    let chosen = select_shell_candidate_with(&plan, &env, "win32", &only_ps).unwrap();
    assert_eq!(
        chosen.program,
        r"C:\Windows\System32\WindowsPowerShell\v1.0\powershell.exe"
    );
    assert_eq!(chosen.args, plan.args);

    // A pwsh batch shim found first is skipped, not wrapped.
    let shim_env = win_env(r"C:\shims;C:\Windows\System32\WindowsPowerShell\v1.0", None);
    let shim = |p: &str| {
        p == r"C:\shims\pwsh.cmd"
            || p == r"C:\Windows\System32\WindowsPowerShell\v1.0\powershell.exe"
    };
    let chosen = select_shell_candidate_with(&plan, &shim_env, "win32", &shim).unwrap();
    assert_eq!(
        chosen.program,
        r"C:\Windows\System32\WindowsPowerShell\v1.0\powershell.exe"
    );

    // PATHEXT order and case-insensitive lookup of the variable name.
    let ext_env = win_env(r"C:\bin", Some(".BAT;.EXE"));
    let bat_first = |p: &str| p == r"C:\bin\pwsh.bat" || p == r"C:\bin\pwsh.exe";
    let chosen = select_shell_candidate_with(&plan, &ext_env, "win32", &bat_first);
    // pwsh resolves to the .bat shim first -> skipped; powershell.exe does not resolve.
    assert_eq!(chosen.unwrap().program, "powershell.exe");

    // Nothing resolves: keep the first candidate's bare name (spawn reports the missing shell).
    let none = |_: &str| false;
    let chosen = select_shell_candidate_with(&plan, &env, "win32", &none).unwrap();
    assert_eq!(chosen.program, "pwsh");

    // Every candidate is a batch shim: nothing runnable.
    let all_shims = |p: &str| p == r"C:\shims\pwsh.cmd" || p == r"C:\shims\powershell.exe.cmd";
    let only_shims_env = win_env(r"C:\shims", None);
    let all_shim_plan = ShellExecutionPlan {
        candidates: vec![ShellCandidate {
            program: "pwsh".to_owned(),
            args: Vec::new(),
        }],
        ..plan.clone()
    };
    assert!(
        select_shell_candidate_with(&all_shim_plan, &only_shims_env, "win32", &all_shims).is_none()
    );
}

#[test]
fn candidate_selection_on_posix_skips_missing_shells() {
    let mut env = HashMap::new();
    env.insert("PATH".to_owned(), "/opt/none:/usr/local/bin".to_owned());
    let plan = build_non_login_shell_plan("echo hi", &env, "linux");
    let only_sh = |p: &str| p == "/usr/local/bin/sh";
    let chosen = select_shell_candidate_with(&plan, &env, "linux", &only_sh).unwrap();
    assert_eq!(chosen.program, "/usr/local/bin/sh");
    assert_eq!(chosen.args, vec!["-c".to_owned(), "echo hi".to_owned()]);
}

#[test]
fn temp_script_is_written_before_spawn_and_removed_afterwards() {
    let dir = tempfile::tempdir().expect("tempdir");
    let path = dir.path().join("cowork-shell-test.ps1");
    let content = format!("\u{feff}{}", powershell_script("echo ü"));
    let plan = ShellExecutionPlan {
        program: "pwsh".to_owned(),
        args: Vec::new(),
        candidates: Vec::new(),
        display_command: "echo ü".to_owned(),
        temp_script: Some(ShellTempScript {
            path: path.clone(),
            content: content.clone(),
        }),
    };
    let guard = materialize_temp_script(&plan)
        .expect("write")
        .expect("guard");
    assert_eq!(guard.path(), path);
    let bytes = std::fs::read(&path).expect("script written");
    assert_eq!(&bytes[..3], &[0xEF, 0xBB, 0xBF], "UTF-8 BOM first");
    assert_eq!(bytes, content.as_bytes());
    drop(guard);
    assert!(!path.exists(), "temp script removed when the run settles");

    let no_script = ShellExecutionPlan {
        temp_script: None,
        ..plan
    };
    assert!(materialize_temp_script(&no_script).expect("noop").is_none());
}
